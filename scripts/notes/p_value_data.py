#!/usr/bin/env python3
"""Simulated data for the note on interpreting the p-value.

The note describes a fictional study: BMI for 286 people who don't eat sugar
(mean 22.4) and 300 who do (mean 30.1). This script simulates that data with
a fixed seed, so the figures are reproducible, and writes:

  _data/p_value_study.yml                     summary used by the note's widgets
  _includes/notes/p-value/histogram.svg       the histogram, as inline SVG

    python3 scripts/notes/p_value_data.py

Standard library only.
"""

from __future__ import annotations

import math
import random
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent.parent
SEED = 2017

GROUPS = [
    # key, n, mean, standard deviation
    ("none", 286, 22.4, 3.4),
    ("sugar", 300, 30.1, 4.8),
]


def simulate(n: int, mean: float, sd: float, rng: random.Random) -> list[float]:
    """Normal values rescaled to have exactly the stated mean and SD."""
    xs = [rng.gauss(0, 1) for _ in range(n)]
    m = sum(xs) / n
    s = math.sqrt(sum((x - m) ** 2 for x in xs) / (n - 1))
    return [mean + sd * (x - m) / s for x in xs]


def welch(a: list[float], b: list[float]) -> tuple[float, float, float, float]:
    """Difference in means, its standard error, t and degrees of freedom."""
    na, nb = len(a), len(b)
    ma, mb = sum(a) / na, sum(b) / nb
    va = sum((x - ma) ** 2 for x in a) / (na - 1)
    vb = sum((x - mb) ** 2 for x in b) / (nb - 1)
    se = math.sqrt(va / na + vb / nb)
    df = (va / na + vb / nb) ** 2 / ((va / na) ** 2 / (na - 1) + (vb / nb) ** 2 / (nb - 1))
    return mb - ma, se, (mb - ma) / se, df


def histogram_svg(samples: dict[str, list[float]], means: dict[str, float]) -> str:
    lo, hi, width = 10, 46, 1
    bins = list(range(lo, hi, width))
    counts = {k: [sum(1 for x in xs if b <= x < b + width) for b in bins] for k, xs in samples.items()}
    top = max(max(c) for c in counts.values())
    y_max = math.ceil(top / 10) * 10

    W, H = 640, 300
    left, right, top_pad, bottom = 44, 16, 40, 44
    pw, ph = W - left - right, H - top_pad - bottom
    sx = lambda v: left + (v - lo) / (hi - lo) * pw
    sy = lambda c: top_pad + ph - c / y_max * ph

    es = "{% if page.lang == 'es-ES' %}"
    el = "{% else %}"
    end = "{% endif %}"
    out = [
        "{%- comment -%} Generated by scripts/notes/p_value_data.py. Don't edit by hand. {%- endcomment -%}",
        f'<svg class="pv-hist" viewBox="0 0 {W} {H}" role="img" aria-labelledby="pv-hist-title">',
        f'<title id="pv-hist-title">{es}Histograma del IMC: el grupo que no consume azúcar se concentra alrededor de 22.4 y el que sí lo consume, alrededor de 30.1, con bastante solapamiento entre ambos.{el}BMI histogram: the group that doesn’t eat sugar clusters around 22.4 and the group that does clusters around 30.1, with a fair amount of overlap.{end}</title>',
    ]
    for t in range(0, y_max + 1, 10):
        y = sy(t)
        out.append(f'<line class="pv-hist__grid" x1="{left}" x2="{W - right}" y1="{y:.1f}" y2="{y:.1f}"/>')
        out.append(f'<text class="pv-hist__tick" x="{left - 8}" y="{y + 4:.1f}" text-anchor="end">{t}</text>')
    for v in range(lo, hi + 1, 5):
        out.append(f'<text class="pv-hist__tick" x="{sx(v):.1f}" y="{H - bottom + 18}" text-anchor="middle">{v}</text>')
    out.append(f'<text class="pv-hist__axis" x="{left + pw / 2:.1f}" y="{H - 6}" text-anchor="middle">{es}IMC (kg/m²){el}BMI (kg/m²){end}</text>')
    out.append(f'<text class="pv-hist__axis" x="12" y="{top_pad + ph / 2:.1f}" text-anchor="middle" transform="rotate(-90 12 {top_pad + ph / 2:.1f})">{es}Personas{el}People{end}</text>')

    i = 0
    for key in ("none", "sugar"):
        out.append(f'<g class="pv-hist__series pv-hist__series--{key}">')
        for b, c in zip(bins, counts[key]):
            if c:
                x0, x1 = sx(b), sx(b + width)
                out.append(
                    f'<rect class="pv-hist__bar" style="--i:{i}" x="{x0 + 0.5:.1f}" y="{sy(c):.1f}" '
                    f'width="{x1 - x0 - 1:.1f}" height="{sy(0) - sy(c):.1f}"/>'
                )
                i += 1
        out.append("</g>")

    for key, label_y in (("none", top_pad - 18), ("sugar", top_pad - 18)):
        x = sx(means[key])
        out.append(f'<g class="pv-hist__mean pv-hist__mean--{key}">')
        out.append(f'<line x1="{x:.1f}" x2="{x:.1f}" y1="{top_pad - 10}" y2="{sy(0):.1f}"/>')
        out.append(f'<text x="{x:.1f}" y="{label_y}" text-anchor="middle">x̄ = {means[key]:.1f}</text>')
        out.append("</g>")

    out.append(f'<line class="pv-hist__baseline" x1="{left}" x2="{W - right}" y1="{sy(0):.1f}" y2="{sy(0):.1f}"/>')
    out.append("</svg>")
    return "\n".join(out) + "\n"


def main() -> None:
    rng = random.Random(SEED)
    samples = {key: simulate(n, mean, sd, rng) for key, n, mean, sd in GROUPS}
    means = {key: mean for key, _, mean, _ in GROUPS}
    diff, se, t, df = welch(samples["none"], samples["sugar"])
    p = math.erfc(abs(t) / math.sqrt(2))  # normal approximation; df is large

    data = ROOT / "_data/p_value_study.yml"
    data.write_text(
        "# Generated by scripts/notes/p_value_data.py. Don't edit by hand.\n"
        "# Simulated study for the note on the p-value (fictional data).\n"
        + "".join(f"{key}: {{n: {n}, mean: {mean}, sd: {sd}}}\n" for key, n, mean, sd in GROUPS)
        + f"difference: {diff:.1f}\nse: {se:.4f}\nt: {t:.1f}\ndf: {df:.0f}\n",
        encoding="utf-8",
    )
    svg = ROOT / "_includes/notes/p-value/histogram.svg"
    svg.write_text(histogram_svg(samples, means), encoding="utf-8")
    print(f"difference {diff:.2f}, SE {se:.4f}, t {t:.2f}, df {df:.0f}, p ≈ {p:.1e}")
    print(f"wrote {data.relative_to(ROOT)} and {svg.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
