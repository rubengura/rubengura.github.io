#!/usr/bin/env python3
"""Figures for the note on pivot tables with dbt.

Reads _data/pokemon_types.json (written by pivot_data.py, from the Kaggle
dataset) and writes:

  _data/dbt_pivot.yml                          how often each second type appears
  _includes/notes/dbt-pivot/handwritten.html   the hand-written query, with the
                                               parts that change on each line marked
  _includes/notes/dbt-pivot/compiled.html      what dbt_utils.pivot() compiles to

    python3 scripts/notes/dbt_pivot_data.py

The note's claims were checked by compiling and running its models with dbt
(dbt-core 1.12, dbt-duckdb, dbt_utils 1.4): the Jinja loop compiles to the
hand-written query, and the dbt_utils version returns the same counts.
Standard library only.
"""

from __future__ import annotations

import json
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent.parent
OUT = ROOT / "_includes/notes/dbt-pivot"
HEADER = "{%- comment -%} Generated by scripts/notes/dbt_pivot_data.py. Don't edit by hand. {%- endcomment -%}\n"

k = lambda w: f'<span class="k">{w}</span>'
n = lambda v: f'<span class="mi">{v}</span>'


def handwritten(types: list[str]) -> str:
    """The query from the previous note, highlighted like Rouge would, with
    the type in each line wrapped in .dp-var."""
    width = max(len(t) for t in types)
    lines = [k("SELECT"), ' "Type1"']
    for i, t in enumerate(types):
        pad = " " * (width - len(t))
        lines.append(
            f' , {k("SUM")}({k("CASE")} {k("WHEN")} "Type2" = <span class="s1">\'<span class="dp-var" style="--i: {i}">{t}</span>\'</span> '
            f'{k("THEN")} {n(1)} {k("ELSE")} {n(0)} {k("END")}){pad} {k("AS")} <span class="dp-var dp-var--name" style="--i: {i}">{t}</span>')
    lines.append(f' , {k("SUM")}({k("CASE")} {k("WHEN")} "Type2" {k("IS")} {k("NULL")} {k("THEN")} {n(1)} {k("ELSE")} {n(0)} {k("END")})      {k("AS")} blank')
    lines += [f'{k("FROM")} dwh_dbt.pokemon_stats', f'{k("GROUP")} {k("BY")} {n(1)}', f'{k("ORDER")} {k("BY")} {n(1)};']
    return (HEADER + '<div class="language-sql highlighter-rouge dp-pattern" data-dp="pattern"><div class="highlight">'
            '<pre class="highlight"><code>' + "\n".join(lines) + "</code></pre></div></div>\n")


def compiled(order: list[str]) -> str:
    lines = [k("SELECT"), '    "Type1"']
    for i, t in enumerate(order):
        lines.append(f'    , {k("sum")}({k("case")} {k("when")} "Type2" = <span class="s1">\'{t}\'</span> '
                     f'{k("then")} {n(1)} {k("else")} {n(0)} {k("end")}) {k("as")} "{t}"')
    lines.append(f'    , {k("SUM")}({k("CASE")} {k("WHEN")} "Type2" {k("IS")} {k("NULL")} {k("THEN")} {n(1)} {k("ELSE")} {n(0)} {k("END")}) {k("AS")} blank')
    lines += [f'{k("FROM")} dwh_dbt.pokemon_stats', f'{k("GROUP")} {k("BY")} {n(1)}', f'{k("ORDER")} {k("BY")} {n(1)}']
    return (HEADER + '<div class="language-sql highlighter-rouge"><div class="highlight"><pre class="highlight"><code>'
            + "\n".join(lines) + "</code></pre></div></div>\n")


def main() -> None:
    data = json.loads((ROOT / "_data/pokemon_types.json").read_text(encoding="utf-8"))
    types = data["types"]
    counts = Counter(p[2] for p in data["pokemon"] if p[2])
    nulls = sum(1 for p in data["pokemon"] if not p[2])
    # get_column_values orders by count(*) desc; ties have no fixed order,
    # so they're shown alphabetically here.
    order = sorted(counts, key=lambda t: (-counts[t], t))

    lines = ["# Generated by scripts/notes/dbt_pivot_data.py. Don't edit by hand.",
             f"with_second_type: {sum(counts.values())}", f"without_second_type: {nulls}", "values:"]
    lines += [f"  - {{type: {t}, n: {counts[t]}}}" for t in order]
    (ROOT / "_data/dbt_pivot.yml").write_text("\n".join(lines) + "\n", encoding="utf-8")

    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / "handwritten.html").write_text(handwritten(types), encoding="utf-8")
    (OUT / "compiled.html").write_text(compiled(order), encoding="utf-8")
    print(f"{sum(counts.values())} rows with a second type, {nulls} without; order: {', '.join(order)}")


if __name__ == "__main__":
    main()
