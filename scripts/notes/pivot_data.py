#!/usr/bin/env python3
"""Data and figures for the note on pivot tables in SQL.

The note uses the "Pokemon with stats" dataset from Kaggle
(https://www.kaggle.com/datasets/abcsds/pokemon). The CSV isn't kept in this
repository: download Pokemon.csv and pass its path. The script runs the
note's two queries in Python, checks the dataset is the one the note
describes, and writes the results the note shows:

  _data/pokemon_pivot.yml                  counts, totals and the preview rows
  _data/pokemon_types.json                 name, type 1, type 2 of every row (for the pivot machine)
  _includes/notes/pivot/step1.html         result of the first query (first rows)
  _includes/notes/pivot/step2.html         result of the second query
  _includes/notes/pivot/heatmap.html       the pivot table as a heatmap

    python3 scripts/notes/pivot_data.py path/to/Pokemon.csv

Standard library only.
"""

from __future__ import annotations

import csv
import html
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent.parent
OUT = ROOT / "_includes/notes/pivot"

TYPES = ["Bug", "Dark", "Dragon", "Electric", "Fairy", "Fighting", "Fire", "Flying", "Ghost",
         "Grass", "Ground", "Ice", "Normal", "Poison", "Psychic", "Rock", "Steel", "Water"]
ES = "{% if page.lang == 'es-ES' %}"
EL = "{% else %}"
END = "{% endif %}"


def load(path: Path) -> list[dict]:
    with path.open(encoding="utf-8") as f:
        rows = list(csv.DictReader(f))
    # Check it's the dataset the note describes
    assert len(rows) == 800, f"expected 800 rows, found {len(rows)}"
    assert (rows[0]["Name"], rows[0]["Type 1"], rows[0]["Type 2"]) == ("Bulbasaur", "Grass", "Poison")
    assert sorted({r["Type 2"] for r in rows if r["Type 2"]}) == TYPES
    assert sorted({r["Type 1"] for r in rows}) == TYPES
    return rows


def result_grid(title: str, headers: list[str], rows: list[list], cell_class, foot: str = "") -> str:
    """A query result as a compact grid, like a database client shows it.
    Columns after the first get a 3-letter header (full name on hover)."""
    out = ['<div class="pt-window pt-result">',
           f'<div class="pt-window__bar" aria-hidden="true"><span></span><span></span><span></span><span class="pt-window__title">{title}</span></div>',
           f'<div class="pt-scroll" tabindex="0" role="region" aria-label="{title}">',
           '<table class="pt-result__grid"><thead><tr>',
           f'<th scope="col">{headers[0]}</th>']
    out += [f'<th scope="col"><abbr title="{h}">{h[:3]}</abbr></th>' for h in headers[1:]]
    out.append("</tr></thead><tbody>")
    for r in rows:
        out.append(f'<tr><th scope="row">{html.escape(str(r[0]))}</th>'
                   + "".join(f'<td{cell_class(v)}>{v}</td>' for v in r[1:]) + "</tr>")
    out.append("</tbody></table></div>")
    if foot:
        out.append(f'<p class="pt-result__foot">{foot}</p>')
    out.append("</div>")
    return "\n".join(out)


def main() -> None:
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    rows = load(Path(sys.argv[1]))
    cols = [t.lower() for t in TYPES] + ["blank"]

    def flags(r):
        return [int(r["Type 2"] == t) for t in TYPES] + [int(r["Type 2"] == "")]

    # Query 1: one row per Pokémon, a 0/1 column per second type
    first = rows[:10]
    step1 = result_grid(
        f"{ES}Resultado · 800 filas{EL}Result · 800 rows{END}", ["Type1"] + cols,
        [[r["Type 1"]] + flags(r) for r in first],
        lambda v: ' class="pt-on"' if v == 1 else ' class="pt-zero"',
        foot=f"{ES}… y 790 filas más{EL}… and 790 more rows{END}")

    # Query 2: the same columns summed, grouped by the first type
    pivot = {t1: [0] * (len(TYPES) + 1) for t1 in TYPES}
    for r in rows:
        for i, f in enumerate(flags(r)):
            pivot[r["Type 1"]][i] += f
    step2 = result_grid(
        f"{ES}Resultado · 18 filas{EL}Result · 18 rows{END}", ["Type1"] + cols,
        [[t] + pivot[t] for t in TYPES],
        lambda v: ' class="pt-n"' if v else ' class="pt-zero"')

    for name, body in (("step1", step1), ("step2", step2)):
        (OUT / f"{name}.html").write_text(
            "{%- comment -%} Generated by scripts/notes/pivot_data.py. Don't edit by hand. {%- endcomment -%}\n"
            + body + "\n", encoding="utf-8")

    # The pivot table as a heatmap (rows: type 1, columns: type 2)
    max_cell = max(max(v[:-1]) for v in pivot.values())
    col_totals = [sum(pivot[t][i] for t in TYPES) for i in range(len(TYPES) + 1)]
    out = ["{%- comment -%} Generated by scripts/notes/pivot_data.py. Don't edit by hand. {%- endcomment -%}",
           '<table class="pt-heat">', "<thead><tr>",
           f'<th scope="col" class="pt-heat__corner"><span>Type1</span> <span>Type2</span></th>']
    for t in TYPES:
        out.append(f'<th scope="col" class="pt-heat__col" style="--type: var(--t-{t.lower()})"><abbr title="{t}">{t[:3]}</abbr></th>')
    out.append(f'<th scope="col" class="pt-heat__col pt-heat__extra"><abbr title="{ES}Sin segundo tipo{EL}No second type{END}">—</abbr></th>')
    out.append('<th scope="col" class="pt-heat__col pt-heat__extra">Σ</th></tr></thead><tbody>')
    for r, t1 in enumerate(TYPES):
        out.append(f'<tr><th scope="row" class="pt-heat__row"><span class="pt-badge" style="--type: var(--t-{t1.lower()})">{t1}</span></th>')
        for c, t2 in enumerate(TYPES):
            v = pivot[t1][c]
            hot = ' class="is-hot"' if v / max_cell > 0.5 else ""
            out.append(f'<td{hot} style="--v: {v / max_cell:.3f}; --d: {r + c}" title="{t1} · {t2}: {v}">{v or ""}</td>')
        v = pivot[t1][-1]
        out.append(f'<td class="pt-heat__extra" style="--d: {r + len(TYPES)}" title="{t1} · —: {v}">{v}</td>')
        out.append(f'<td class="pt-heat__extra pt-heat__total" style="--d: {r + len(TYPES) + 1}">{sum(pivot[t1])}</td></tr>')
    out.append('</tbody><tfoot><tr><th scope="row" class="pt-heat__row">Σ</th>')
    for i, v in enumerate(col_totals):
        extra = ' class="pt-heat__extra"' if i == len(TYPES) else ""
        out.append(f'<td{extra}>{v}</td>')
    out.append(f'<td class="pt-heat__extra pt-heat__total">{len(rows)}</td></tr></tfoot></table>')
    (OUT / "heatmap.html").write_text("\n".join(out) + "\n", encoding="utf-8")

    # Summary and preview rows
    preview = rows[:8]
    lines = ["# Generated by scripts/notes/pivot_data.py. Don't edit by hand.",
             "# \"Pokemon with stats\" (Kaggle, abcsds/pokemon): figures for the pivot table note.",
             f"rows: {len(rows)}", f"no_second_type: {col_totals[-1]}", f"max_cell: {max_cell}",
             "types: [" + ", ".join(TYPES) + "]", "preview:"]
    for r in preview:
        lines.append(f'  - {{name: "{r["Name"]}", type1: {r["Type 1"]}, type2: "{r["Type 2"]}", total: {r["Total"]}, '
                     f'hp: {r["HP"]}, attack: {r["Attack"]}, defense: {r["Defense"]}, speed: {r["Speed"]}}}')
    (ROOT / "_data/pokemon_pivot.yml").write_text("\n".join(lines) + "\n", encoding="utf-8")

    (ROOT / "_data/pokemon_types.json").write_text(
        json.dumps({"types": TYPES, "pokemon": [[r["Name"], r["Type 1"], r["Type 2"]] for r in rows]},
                   ensure_ascii=False, separators=(",", ":")) + "\n", encoding="utf-8")

    print(f"{len(rows)} rows, {col_totals[-1]} without a second type, largest cell {max_cell}")
    top = sorted(((pivot[a][i], a, b) for a in TYPES for i, b in enumerate(TYPES)), reverse=True)[:3]
    print("most common pairs:", top)
    print(f"wrote _data/pokemon_pivot.yml, _data/pokemon_types.json and {OUT.relative_to(ROOT)}/")


if __name__ == "__main__":
    main()
